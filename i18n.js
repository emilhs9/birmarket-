let currentLanguage = localStorage.getItem('birmarket_lang') || 'az';

function t(key) {
  if (i18nTranslations[currentLanguage] && i18nTranslations[currentLanguage][key]) {
    return i18nTranslations[currentLanguage][key];
  }
  return i18nTranslations['az'][key] || key;
}

function applyTranslations() {
  document.documentElement.lang = currentLanguage;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key && i18nTranslations[currentLanguage] && i18nTranslations[currentLanguage][key]) {
      el.textContent = i18nTranslations[currentLanguage][key];
    }
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (key && i18nTranslations[currentLanguage] && i18nTranslations[currentLanguage][key]) {
      el.innerHTML = i18nTranslations[currentLanguage][key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key && i18nTranslations[currentLanguage] && i18nTranslations[currentLanguage][key]) {
      el.setAttribute('placeholder', i18nTranslations[currentLanguage][key]);
    }
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key && i18nTranslations[currentLanguage] && i18nTranslations[currentLanguage][key]) {
      el.setAttribute('title', i18nTranslations[currentLanguage][key]);
    }
  });

  const footerAz = document.getElementById('footer-lang-az');
  const footerRu = document.getElementById('footer-lang-ru');

  if (footerAz && footerRu) {
    if (currentLanguage === 'az') {
      footerAz.className = 'cursor-pointer text-[#1E244D] font-bold transition-colors';
      footerRu.className = 'cursor-pointer text-[#8C93A4] font-normal hover:text-[#1E244D] transition-colors';
    } else {
      footerAz.className = 'cursor-pointer text-[#8C93A4] font-normal hover:text-[#1E244D] transition-colors';
      footerRu.className = 'cursor-pointer text-[#1E244D] font-bold transition-colors';
    }
  }

  const headerImg = document.getElementById('header-lang-img');
  const headerText = document.getElementById('header-lang-text');
  if (headerImg) {
    headerImg.src = currentLanguage === 'az' ? 'img/flag_az.svg' : 'img/flag_ru.svg';
    headerImg.title = currentLanguage.toUpperCase();
  }
  if (headerText) {
    headerText.textContent = currentLanguage.toUpperCase();
  }

  if (typeof window.onLanguageChange === 'function') {
    window.onLanguageChange(currentLanguage);
  }
}

function setLanguage(lang) {
  if (lang !== 'az' && lang !== 'ru') return;
  currentLanguage = lang;
  localStorage.setItem('birmarket_lang', lang);
  applyTranslations();
}

document.addEventListener('DOMContentLoaded', () => {
  applyTranslations();

  const footerAz = document.getElementById('footer-lang-az');
  const footerRu = document.getElementById('footer-lang-ru');

  if (footerAz) {
    footerAz.addEventListener('click', () => setLanguage('az'));
  }
  if (footerRu) {
    footerRu.addEventListener('click', () => setLanguage('ru'));
  }

  const langSelectBtn = document.querySelector('.LangSelect-Button');
  const langDropdown = document.querySelector('.LangSelect-Dropdown');
  const langArrow = document.querySelector('.LangSelect-Arrow');

  if (langSelectBtn && langDropdown) {
    langSelectBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      const isHidden = langDropdown.style.display === 'none' || !langDropdown.style.display;
      langDropdown.style.display = isHidden ? 'block' : 'none';
      if (langArrow) {
        langArrow.style.transform = isHidden ? 'rotate(180deg)' : 'rotate(0deg)';
      }
    });

    document.addEventListener('click', () => {
      langDropdown.style.display = 'none';
      if (langArrow) {
        langArrow.style.transform = 'rotate(0deg)';
      }
    });

    document.querySelectorAll('[data-set-lang]').forEach(item => {
      item.addEventListener('click', (e) => {
        e.stopPropagation();
        const selectedLang = item.getAttribute('data-set-lang');
        setLanguage(selectedLang);
        langDropdown.style.display = 'none';
        if (langArrow) {
          langArrow.style.transform = 'rotate(0deg)';
        }
      });
    });
  }
});

